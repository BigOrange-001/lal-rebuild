"""Pack 20 imagegen center icons; the game draws its native rainbow frame.

PNG sources stay reviewable. Only geometric contain/atlas packing is applied.
One shared bitmap/texture (with context restoration), no per-icon uploads.
"""
from pathlib import Path
import hashlib
import json
import zlib
from PIL import Image

ROOT=Path(__file__).resolve().parents[1]
SOURCE=ROOT/'client/resources/abyss-relics'
PART=ROOT/'client/src/abyss_relic_art_104.aspart'
NAMES=['不灭圣盾','先声夺人','坚守誓约','复苏之羽','荆棘之躯','疾风步','嗜血','破军','斩首','余烬',
       '剧毒','碎盾','寒霜','圣佑','坚城','统御','同心','召唤契约','时之沙','真理之刃']


def build():
    atlas=Image.new('RGBA',(512,512))
    metadata=[]
    for index in range(20):
        path=SOURCE/f'abyss_relic_{index+1:02d}.png'
        image=Image.open(path).convert('RGBA')
        bounds=image.getbbox()
        if not bounds:raise ValueError(f'Empty icon: {path}')
        if image.getchannel('A').getextrema()[0]!=0:raise ValueError(f'Icon must be transparent: {path}')
        image=image.crop(bounds)
        image.thumbnail((76,77),Image.Resampling.LANCZOS)
        x=(index%5)*100+(92-image.width)//2
        y=(index//5)*100+(93-image.height)//2
        atlas.alpha_composite(image,(x,y))
        metadata.append({'relic_id':index+1,'name':NAMES[index],'file':path.name,'sha256':hashlib.sha256(path.read_bytes()).hexdigest(),
                         'region':[(index%5)*100,(index//5)*100,92,93]})
    atlas.save(SOURCE/'atlas.png')
    rgba=atlas.tobytes();argb=bytearray(len(rgba))
    for destination,source in enumerate((3,0,1,2)):argb[destination::4]=rgba[source::4]
    packed=zlib.compress(bytes(argb),9)
    chunks=',\n'.join('            "'+packed.hex()[i:i+4096]+'"' for i in range(0,len(packed)*2,4096))
    PART.write_text('''// Generated by scripts/build_abyss_relic_art_104.py; do not edit pixel data.
class AbyssRelicArt104
{
   public static function create(item:Object, size:Number = 92) : Sprite
   {
      var holder:Sprite = new Sprite();
      holder.touchable = false;
      var background:Quad = new Quad(92,93,0x291530);
      holder.addChild(background);
      var kind:int = item ? int(item.relic_id) : 0;
      if(kind >= 1 && kind <= 20)
      {
         var texture:Texture = Texture.fromTexture(atlas(),new Rectangle(((kind - 1) % 5) * 100,int((kind - 1) / 5) * 100,92,93));
         holder.addChild(new Image(texture));
      }
      holder.addChild(Equip.createRainbowFrame104());
      holder.scaleX = holder.scaleY = size / 92;
      return holder;
   }

   private static function atlas() : Texture
   {
      var texture:Texture = GlobalData.$assetManager.getTexture("__abyssRelicAtlas104");
      if(!texture)
      {
         var encoded:String = [
CHUNKS].join("");
         var bytes:ByteArray = new ByteArray();
         for(var offset:int = 0; offset < encoded.length; offset += 2) bytes.writeByte(parseInt(encoded.substr(offset,2),16));
         bytes.uncompress();
         bytes.position = 0;
         var bitmap:BitmapData = new BitmapData(512,512,true,0);
         bitmap.setPixels(new Rectangle(0,0,512,512),bytes);
         bytes.clear();
         texture = Texture.fromBitmapData(bitmap,false,false);
         texture.root.onRestore = function():void { texture.root.uploadBitmapData(bitmap); };
         GlobalData.$assetManager.addTexture("__abyssRelicAtlas104",texture);
      }
      return texture;
   }
}
'''.replace('CHUNKS',chunks),'utf-8')
    (SOURCE/'manifest.json').write_text(json.dumps({'schema':1,'atlas':[512,512],'icon':[92,93],
        'frame':'native Equip.createRainbowFrame104 (48 frames, 20 fps)',
        'argb_sha256':hashlib.sha256(argb).hexdigest(),'icons':metadata},ensure_ascii=False,indent=2)+'\n','utf-8')
    print(f'Packed 20 relic icons: {len(packed)} compressed bytes')


if __name__=='__main__':build()
