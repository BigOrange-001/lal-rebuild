"""Resize the imagegen master and embed the native-size icon in Equip.

Usage: python scripts/build_stardust_icon.py [--master PATH]
The checked-in master is generated art; this script only crops and resamples it.
"""
from pathlib import Path
import argparse
import hashlib
import json
import re
import shutil
import zlib
from PIL import Image, ImageOps

ROOT = Path(__file__).resolve().parents[1]
ART = ROOT / 'client/resources/currency'
SOURCE = ROOT / 'client/src/stages/084_Equip.as'


def build(master=None):
    ART.mkdir(parents=True, exist_ok=True)
    saved = ART / 'stardust-master.png'
    if master and Path(master).resolve() != saved.resolve():
        shutil.copyfile(master, saved)
    image = Image.open(saved).convert('RGBA')
    # Exclude almost-invisible export noise from the crop, preserving all alpha
    # in the selected rectangle and resampling in premultiplied-alpha space.
    bounds = image.getchannel('A').point(lambda a: 255 if a > 1 else 0).getbbox()
    if bounds is None:
        raise ValueError('Empty stardust master')
    small = ImageOps.contain(image.crop(bounds).convert('RGBa'), (50, 48), Image.Resampling.LANCZOS).convert('RGBA')
    icon = Image.new('RGBA', (52, 50))
    icon.alpha_composite(small, ((52-small.width)//2, (50-small.height)//2))
    icon.save(ART / 'stardust-52x50.png', optimize=True)
    rgba = icon.tobytes()
    argb = bytearray(len(rgba))
    for channel, original in enumerate((3, 0, 1, 2)):
        argb[channel::4] = rgba[original::4]
    packed = zlib.compress(bytes(argb), 9).hex()
    chunks = ',\n'.join('               "'+packed[i:i+2048]+'"' for i in range(0, len(packed), 2048))
    method = '''      // BEGIN GENERATED STARDUST ICON
      // Generated by scripts/build_stardust_icon.py from the native 52x50 PNG.
      public static function createStardustIcon() : Image
      {
         var texture:Texture = GlobalData.$assetManager.getTexture("__stardustIcon105");
         if(!texture)
         {
            var encoded:String = [
CHUNKS].join("");
            var bytes:ByteArray = new ByteArray();
            for(var offset:int = 0; offset < encoded.length; offset += 2)
               bytes.writeByte(parseInt(encoded.substr(offset,2),16));
            bytes.uncompress();
            bytes.position = 0;
            var bitmap:BitmapData = new BitmapData(52,50,true,0);
            bitmap.setPixels(new Rectangle(0,0,52,50),bytes);
            bytes.clear();
            texture = Texture.fromBitmapData(bitmap,false,false);
            texture.root.onRestore = function():void { texture.root.uploadBitmapData(bitmap); };
            GlobalData.$assetManager.addTexture("__stardustIcon105",texture);
         }
         var icon:Image = new Image(texture);
         icon.name = "stardustIcon";
         icon.touchable = false;
         icon.scaleX = icon.scaleY = 0.6;
         return icon;
      }
      // END GENERATED STARDUST ICON

'''.replace('CHUNKS', chunks)
    source = SOURCE.read_text('utf8')
    if '// BEGIN GENERATED STARDUST ICON' in source:
        source = re.sub(r'      // BEGIN GENERATED STARDUST ICON.*?      // END GENERATED STARDUST ICON\n\n', lambda _: method, source, flags=re.S)
    else:
        source = source.replace('      public static function getStardustBalance()', method+'      public static function getStardustBalance()', 1)
    SOURCE.write_text(source, encoding='utf8', newline='\r\n')
    metadata = dict(width=52, height=50, display_scale=0.6,
                    reference='UI_magic_money_0000..0003: 52x50; PanelEquipSellSelect.getDustUIs scale=0.6',
                    crop=list(bounds), imagegen_mode='built-in',
                    master_sha256=hashlib.sha256(saved.read_bytes()).hexdigest(),
                    png_sha256=hashlib.sha256((ART/'stardust-52x50.png').read_bytes()).hexdigest(),
                    argb_sha256=hashlib.sha256(bytes(argb)).hexdigest())
    (ART/'stardust.json').write_text(json.dumps(metadata, ensure_ascii=False, indent=2)+'\n', 'utf8')
    print(json.dumps(metadata))


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--master', type=Path)
    build(parser.parse_args().master)
