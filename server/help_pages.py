def _render(title: str, intro: str, sections: list[tuple[str, str, str | None]], *, notice: bool = False) -> bytes:
    safe_title = escape(title, quote=True)
    safe_intro = escape(intro, quote=True)
    body = [
        "<!doctype html><html lang=\"zh-CN\"><head><meta charset=\"utf-8\">",
        "<meta name=\"viewport\" content=\"width=device-width,initial-scale=1\">",
        f"<title>{safe_title}</title><style>body{{font-family:system-ui,'Microsoft YaHei',sans-serif;background:#171311;color:#f3e8dc;margin:0;padding:16px;line-height:1.65}}",
        "main{max-width:760px;margin:auto}h1{font-size:22px;margin:0 0 10px;color:#ffd17a}h2{font-size:17px;color:#f0bb68;margin:18px 0 4px}p{margin:5px 0 12px}a{color:#8fc8ff;text-decoration:none}.card{background:#28201c;border:1px solid #59473b;border-radius:8px;padding:12px 14px;margin:10px 0}.muted{color:#c3b2a5;font-size:13px}</style></head><body><main>",
        f"<h1>{safe_title}</h1><p>{safe_intro}</p>",
    ]
    if notice:
        body.append("<div class=\"card\"><h2>单人练习模式</h2><p>可体验单人玩法与训练对手；当前不连接线上游戏服务器，也不会匹配真实玩家。</p></div>")
        body.append("<div class=\"card\"><h2>档位领取</h2><p>档位通过点击领取，直接发放对应数量的金砖，不会发起外部支付。账号首次领取任一档位按界面规则双倍发放，之后按档位正常发放；同一操作重试不会重复到账。</p></div>")
        body.append("<div class=\"card\"><h2>账号存档</h2><p>账号进度、资源和邮件奖励保存在当前服务端存档中。请使用同一账号继续游戏；可以通过游戏内帮助查看玩法规则。遇到问题时记录操作步骤和界面提示，避免公开账号密码。</p></div>")
    for heading, text, slug in sections:
        safe_heading, safe_text = escape(heading, quote=True), escape(text, quote=True)
        body.append(f"<section class=\"card\"><h2>{safe_heading}</h2><p>{safe_text}</p>")
        if slug:
            href = escape(f"/help/{slug}.html/", quote=True)
            body.append(f"<a href=\"{href}\">查看专题说明 →</a>")
        body.append("</section>")
    body.append("</main></body></html>")
    return "".join(body).encode("utf-8")


def render_notice() -> bytes:
    return _render("游戏公告", "欢迎体验单人玩法。各功能开放条件、消耗与奖励请以游戏内页面显示为准。", [], notice=True)


def render_help(path: str) -> bytes:
    parts = [part for part in urlsplit(path).path.split("/") if part]
    slug = None
    for part in parts[1:]:
        if part.endswith(".html"):
            slug = part[:-5]
            break
    missing = bool(slug and slug not in PAGES)
    title, intro, sections = PAGES["help" if missing else (slug or "help")]
    if missing:
        intro = "未找到该专题，下面列出可用帮助内容。未知路径不会执行重定向或接收外部参数。"
        sections = PAGES["help"][2]
    return _render(title, intro, sections)
